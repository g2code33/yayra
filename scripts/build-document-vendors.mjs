#!/usr/bin/env node
/**
 * Build the offline document engines as native browser ESM.
 *
 * Yayra intentionally serves plain ES modules rather than routing local files
 * through a remote conversion service.  esbuild is used only at build time:
 * the generated modules below are copied into every PWA/Electron/Capacitor
 * package and therefore work without a network connection.
 */
import { build } from 'esbuild';
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';

const root = process.cwd();
const source = path.join(root, 'scripts', 'vendor-src');
const output = path.join(root, 'packages', 'shared-ui', 'src', 'vendor', 'documents');
await mkdir(output, { recursive: true });

const common = {
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['chrome109', 'firefox115', 'safari16'],
  legalComments: 'inline',
  charset: 'utf8',
  sourcemap: false,
  minify: false,
  logLevel: 'warning'
};

const entries = [
  ['pptxRenderer.ts', 'pptxRenderer.mjs'],
  ['docxPreviewEntry.js', 'docxPreview.mjs'],
  ['xlsxEntry.js', 'xlsx.mjs'],
  // Loaded only for Word/PowerPoint 97-2003. Minifying this dependency-heavy
  // bridge keeps its lazy offline payload bounded without affecting modern
  // DOCX/PPTX users.
  ['legacyOffice.ts', 'legacyOffice.mjs', { minify: true }],
  // Chromium has no native EMF/WMF decoder. This stays a separate lazy
  // module so ordinary presentations never pay the metafile parser cost.
  ['metafile.ts', 'metafile.mjs', { minify: true }]
];
for (const [entry, outfile, overrides = {}] of entries) {
  await build({
    ...common,
    ...overrides,
    entryPoints: [path.join(source, entry)],
    outfile: path.join(output, outfile),
    banner: { js: '/* Generated by scripts/build-document-vendors.mjs — do not edit by hand. */' }
  });
}

const licences = [
  ['node_modules/jszip/LICENSE.markdown', 'JSZIP-LICENSE.md'],
  ['node_modules/dingbat-to-unicode/LICENSE', 'DINGBAT-TO-UNICODE-LICENSE'],
  ['node_modules/docx-preview/LICENSE', 'DOCX-PREVIEW-LICENSE'],
  ['node_modules/@e965/xlsx/LICENSE', 'E965-XLSX-LICENSE'],
  ['node_modules/emf-converter/LICENSE', 'EMF-CONVERTER-LICENSE'],
  ['node_modules/emf-converter/THIRD_PARTY_NOTICES', 'EMF-CONVERTER-THIRD-PARTY-NOTICES']
];
for (const [from, to] of licences) await copyFile(path.join(root, from), path.join(output, to));
await copyFile(path.join(root, 'LICENSE.reference-pharmatrack'), path.join(output, 'PHARMATRACK-MIT-LICENSE'));

// esbuild tree-shakes this list down to the packages used by the bridge, but
// their notices still need to travel with every offline copy of the module.
// Keep the source list explicit so a dependency update produces a reviewable
// notice diff rather than silently dropping attribution.
const legacyOfficePackages = [
  '@nodable/entities', 'anynum', 'archive-codec', 'byte-codec', 'doc-codec',
  'document-schema.js', 'documents.js', 'excel-number-format',
  'fast-xml-builder', 'fast-xml-parser', 'fflate', 'is-unsafe', 'odf.js',
  'ooxml.js', 'path-expression-matcher', 'ppt-codec', 'strnum', 'xml-naming', 'zod'
];
let legacyNotices = '# Legacy Office viewer — third-party notices\n\n'
  + 'The bundled legacy Office bridge runs locally and contains the following MIT-licensed packages.\n';
for (const packageName of legacyOfficePackages) {
  const packageDir = path.join(root, 'node_modules', ...packageName.split('/'));
  const metadata = JSON.parse(await readFile(path.join(packageDir, 'package.json'), 'utf8'));
  let licenceText = '';
  try { licenceText = (await readFile(path.join(packageDir, 'LICENSE'), 'utf8')).trim(); } catch { /* package omitted its licence file */ }
  legacyNotices += `\n## ${packageName} ${metadata.version}\n\nLicense: ${metadata.license || 'MIT'}\n\n`;
  if (licenceText) legacyNotices += `${licenceText}\n`;
  else legacyNotices += `Package author: ${metadata.author || 'See the package repository metadata'}. The package declares the MIT license.\n`;
}
await writeFile(path.join(output, 'LEGACY-OFFICE-NOTICES.md'), legacyNotices);

const manifest = {};
for (const [, file] of entries) {
  const bytes = await readFile(path.join(output, file));
  manifest[file] = {
    bytes: bytes.byteLength,
    sha256: createHash('sha256').update(bytes).digest('hex')
  };
}
await writeFile(path.join(output, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`built offline document engines (${Object.keys(manifest).join(', ')})`);
